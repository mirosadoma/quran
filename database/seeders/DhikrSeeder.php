     * Run the database seeds.
     */
    public function run(): void
    {
        foreach ($this->adhkar() as $slug => $items) {
            $category = DhikrCategory::query()->where('slug', $slug)->first();

            if ($category === null) {
                continue;
            }

            foreach ($items as $order => $item) {
                Dhikr::query()->firstOrCreate(
                    ['dhikr_category_id' => $category->id, 'title' => $item['title'] ?? null, 'text' => $item['text']],
                    [
                        'repeat' => $item['repeat'] ?? 1,
                        'reference' => $item['reference'] ?? null,
                        'virtue' => $item['virtue'] ?? null,
                        'sort_order' => $order + 1,
                        'is_active' => true,
                    ],
                );
            }
        }
    }

