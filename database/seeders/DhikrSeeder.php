    /**
     * Quranic text word for word from the seeded Quran, each ayah followed by its number.
     * $startAt starts the text at the first word that reads like it (e.g. "ربنا"), to quote only the dua.
     */
    protected function quran(int $surah, int $from, ?int $to = null, ?string $startAt = null): string
    {
        $ayahs = Ayah::query()
            ->where('surah', $surah)
            ->whereBetween('ayah', [$from, $to ?? $from])
            ->orderBy('ayah')
            ->get(['ayah', 'text']);

        if ($ayahs->isEmpty()) {
            throw new RuntimeException('Run AyahSeeder before DhikrSeeder: the Quran text is missing.');
        }

        $parts = $ayahs->map(fn (Ayah $ayah): string => $ayah->text.' ('.$this->arabicDigits($ayah->ayah).')')->all();

        if ($startAt !== null) {
            $words = explode(' ', $parts[0]);
            $needle = explode(' ', Mushaf::normalize($startAt));
            $index = collect(array_keys($words))->first(fn (int $position): bool => array_map(
                fn (string $word): string => Mushaf::normalize($word),
                array_slice($words, $position, count($needle)),
            ) === $needle);

            if ($index === null) {
                throw new RuntimeException("The words {$startAt} are not in {$surah}:{$from}.");
            }

            $parts[0] = implode(' ', array_slice($words, $index));
        }

        return implode(' ', $parts);
    }

    /**
     * A whole short surah preceded by the basmala.
     */
    protected function surah(int $surah): string
    {
        $basmala = Ayah::query()->whereKey(1)->value('text');
        $count = Ayah::query()->where('surah', $surah)->max('ayah');

        return $basmala."\n".$this->quran($surah, 1, (int) $count);
    }

    protected function arabicDigits(int $number): string
    {
        return strtr((string) $number, ['0' => '٠', '1' => '١', '2' => '٢', '3' => '٣', '4' => '٤', '5' => '٥', '6' => '٦', '7' => '٧', '8' => '٨', '9' => '٩']);
    }
